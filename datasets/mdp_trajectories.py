import numpy as np
import torch
from torch.utils.data import Dataset
from typing import Optional, Tuple
from scipy.optimize import linear_sum_assignment
from collections import Counter


class MDPTrajectoriesDataset(Dataset):
    """Dataset for MDP trajectories with uniformly sampled transition matrices.
    
    Each set contains state-action pairs from trajectories generated by a 
    transition matrix uniformly sampled over the simplex.
    """
    
    def __init__(
            self, 
            n_sets: int = 10_000, 
            set_size: int = 100, 
            n_states: int = 10,
            n_actions: int = 10,
            trajectory_length: int = 20,
            seed: Optional[int] = None,
            data_shape: Tuple[int, int] = (40,),
            ):
        """
        Args:
            n_sets: Number of parameter sets to generate
            set_size: Number of trajectories per parameter set
            n_states: Number of states in the MDP
            n_actions: Number of actions in the MDP
            trajectory_length: Length of each trajectory
            seed: Random seed for reproducibility
        """
        self.n_sets = n_sets
        self.set_size = set_size
        self.n_states = n_states
        self.n_actions = n_actions
        self.trajectory_length = trajectory_length
        
        if seed is not None:
            np.random.seed(seed)
            torch.manual_seed(seed)
            
        # Pre-generate all transition matrices efficiently
        self.transition_matrices = self._generate_all_transition_matrices()
        
        # Pre-generate data for all sets (single reservoir)
        self.data = self._generate_all_sets()
        
    def _generate_all_transition_matrices(self):
        """Efficiently generate all transition matrices at once.
        
        Returns:
            Tensor of shape (n_sets, n_states, n_actions, n_states)
        """
        print(f"Generating {self.n_sets} transition matrices...")
        
        # Sample all transition matrices at once using vectorized operations
        # Shape: (n_sets, n_states, n_actions, n_states)
        # Each (s, a) pair gets a Dirichlet(1, 1, ..., 1) distribution over next states
        
        # Generate random samples for Dirichlet distribution
        # Dirichlet(α) can be generated as Gamma(α_i) / sum(Gamma(α_i))
        gamma_samples = np.random.gamma(
            1.0, 1.0, 
            size=(self.n_sets, self.n_states, self.n_actions, self.n_states)
        )
        
        # Normalize to get probabilities (Dirichlet samples)
        transition_matrices = gamma_samples / gamma_samples.sum(axis=-1, keepdims=True)
        
        print(f"Generated transition matrices shape: {transition_matrices.shape}")
        return torch.from_numpy(transition_matrices).float()
    
    def _sample_transition_matrix(self):
        """Sample a single transition matrix (legacy method for compatibility)."""
        gamma_samples = np.random.gamma(1.0, 1.0, size=(self.n_states, self.n_actions, self.n_states))
        transition_matrix = gamma_samples / gamma_samples.sum(axis=-1, keepdims=True)
        return transition_matrix
    
    def _generate_trajectory(self, transition_matrix, start_state=None):
        """Generate a single trajectory using the given transition matrix.
        
        Args:
            transition_matrix: Transition matrix (n_states, n_actions, n_states)
            start_state: Starting state (if None, sample uniformly)
            
        Returns:
            List of (state, action) pairs
        """
        if start_state is None:
            current_state = np.random.randint(0, self.n_states)
        else:
            current_state = start_state
            
        trajectory = []
        
        for _ in range(self.trajectory_length):
            # Sample action uniformly (could be modified to use a policy)
            action = np.random.randint(0, self.n_actions)
            
            # Record state-action pair
            trajectory.append((current_state, action))
            
            # Sample next state according to transition matrix
            next_state_probs = transition_matrix[current_state, action, :]
            current_state = np.random.choice(self.n_states, p=next_state_probs)
            
        return trajectory
    
    def _trajectories_to_tensor(self, trajectories):
        """Convert list of trajectories to tensor format.
        
        Args:
            trajectories: List of trajectories, each trajectory is list of (state, action) pairs
            
        Returns:
            Tensor of shape (set_size, trajectory_length, 2) where last dim is [state, action]
        """
        tensor_data = []
        
        for trajectory in trajectories:
            # Convert trajectory to tensor: (trajectory_length, 2)
            traj_tensor = torch.tensor(trajectory, dtype=torch.long)
            tensor_data.append(traj_tensor)
            
        # Stack into (set_size, trajectory_length, 2)
        return torch.stack(tensor_data)
    
    def _generate_set(self, set_idx):
        """Generate a single set of trajectories from one transition matrix."""
        # Use pre-computed transition matrix for this set
        transition_matrix = self.transition_matrices[set_idx].numpy()
        
        # Generate multiple trajectories using this transition matrix
        trajectories = []
        for _ in range(self.set_size):
            trajectory = self._generate_trajectory(transition_matrix)
            trajectories.append(trajectory)
            
        # Convert to tensor format
        trajectory_tensor = self._trajectories_to_tensor(trajectories)
        
        return trajectory_tensor
        
    def _generate_all_sets(self):
        """Pre-generate all sets of trajectory data using batch processing."""
        print(f"Generating {self.n_sets} sets of MDP trajectory data...")
        
        # Process in batches for better memory efficiency
        batch_size = 100  # Process 100 sets at a time
        all_data = []
        
        for batch_start in range(0, self.n_sets, batch_size):
            batch_end = min(batch_start + batch_size, self.n_sets)
            
            if batch_start % 1000 == 0:
                print(f"Generated {batch_start}/{self.n_sets} sets")
            
            # Generate batch of sets
            batch_data = []
            for set_idx in range(batch_start, batch_end):
                data_set = self._generate_set(set_idx)
                batch_data.append(data_set)
            
            # Stack batch and add to all_data
            if batch_data:
                batch_tensor = torch.stack(batch_data)
                all_data.append(batch_tensor)
            
        # Stack all batches - single reservoir
        data = torch.cat(all_data, dim=0)  # (n_sets, set_size, trajectory_length, 2)
        
        print(f"Generated data shape: {data.shape}")
        
        return data
        
    def __len__(self):
        return self.n_sets
    
    def __getitem__(self, idx):
        """Get a pair of source and target samples."""
        source_idx = idx
        # Sample a random target index from the same reservoir
        target_idx = np.random.choice(self.n_sets)
        
        # Get raw trajectory data and encode to flattened sequences
        source_raw = self.data[source_idx]  # (set_size, trajectory_length, 2)
        target_raw = self.data[target_idx]  # (set_size, trajectory_length, 2)
        
        # Encode to flattened sequences: (set_size, trajectory_length * 2)
        source_encoded = self.encode_state_action_pairs(source_raw)
        target_encoded = self.encode_state_action_pairs(target_raw)
        
        return {
            'source_samples': source_encoded,
            'target_samples': target_encoded,
            'source_idx': source_idx,
            'target_idx': target_idx
        }
    
    def pairwise_dist_fn(self, set1_idx, set2_idx):
        """Compute pairwise distance between two sets using transition matrices.
        
        This function computes distance by:
        1. Getting the transition matrices for both sets
        2. Solving linear assignment to match state labels optimally
        3. Computing Frobenius norm between aligned transition matrices
        
        Args:
            set1_idx: Index of first set
            set2_idx: Index of second set
            
        Returns:
            Distance between the two transition matrices
        """
        # Get transition matrices for both sets
        T1 = self.transition_matrices[set1_idx]  # (n_states, n_actions, n_states)
        T2 = self.transition_matrices[set2_idx]  # (n_states, n_actions, n_states)
        
        return self._transition_matrix_distance(T1, T2)
    
    def _transition_matrix_distance(self, T1, T2):
        """Compute distance between two transition matrices with optimal state alignment.
        
        Args:
            T1, T2: Transition matrices of shape (n_states, n_actions, n_states)
            
        Returns:
            Frobenius norm distance after optimal state permutation
        """
        # Convert to numpy for linear assignment
        T1_np = T1.numpy() if isinstance(T1, torch.Tensor) else T1
        T2_np = T2.numpy() if isinstance(T2, torch.Tensor) else T2
        
        # Compute cost matrix for linear assignment
        # Cost[i,j] = ||T1[i,:,:] - T2[j,:,:]||_F^2 (cost of matching state i to state j)
        cost_matrix = np.zeros((self.n_states, self.n_states))
        
        for i in range(self.n_states):
            for j in range(self.n_states):
                # Compare all action transitions from state i in T1 to state j in T2
                diff = T1_np[i, :, :] - T2_np[j, :, :]
                cost_matrix[i, j] = np.sum(diff ** 2)  # Squared Frobenius norm
        
        # Solve linear assignment problem
        row_indices, col_indices = linear_sum_assignment(cost_matrix)
        
        # Compute aligned distance
        total_distance = 0.0
        for i, j in zip(row_indices, col_indices):
            # Add distance for this state alignment
            diff = T1_np[i, :, :] - T2_np[j, :, :]
            total_distance += np.sum(diff ** 2)
        
        # Return Frobenius norm (square root of sum of squared differences)
        return np.sqrt(total_distance)
    
