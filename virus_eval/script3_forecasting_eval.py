import os
import argparse
from typing import Dict, List, Tuple

import numpy as np
import torch

from virus_eval.utils import (
    setup_file_logger,
    resolve_outputs_dir,
    load_cfg_from_run_dir,
    instantiate_models,
    load_weights,
    encode_source_samples,
    IdxMLP,
)


def _ensure_tensor(x: torch.Tensor) -> torch.Tensor:
    if isinstance(x, torch.Tensor):
        return x
    return torch.as_tensor(x)


def main():
    parser = argparse.ArgumentParser(description="Script 3 (forecasting): Evaluate predictor's 1-step forecasting ability on held-out final timepoint")
    parser.add_argument("outputs_subdir", type=str, help="Subdirectory under ./outputs (or absolute run dir path)")
    parser.add_argument(
        "--dataset_path",
        type=str,
        default="/orcd/archive/abugoot/001/Projects/paolo/CoupledDistributionEmbeddings/virus_eval/dataset_offset_1.npz",
        help="Path to dataset_offset_<OFFSET>.npz generated by script 1",
    )
    parser.add_argument(
        "--heldout_path",
        type=str,
        default="/orcd/archive/abugoot/001/Projects/paolo/CoupledDistributionEmbeddings/data/spikeprot0430/virus_tokenized_data_for_tde_downsampled100.pt",
        help="Path to tokenized PT file containing all timepoints (last entry is held out)",
    )
    parser.add_argument(
        "--models_dir",
        type=str,
        default="/orcd/archive/abugoot/001/Projects/paolo/CoupledDistributionEmbeddings/virus_eval",
        help="Directory where script 2 saved trained models (mlp_sourceidx.pt, ridge_sourceidx.npz)",
    )
    parser.add_argument("--device", type=str, default="cuda" if torch.cuda.is_available() else "cpu")
    parser.add_argument("--num_control_sets", type=int, default=5, help="Number of random sets sampled from held-out timepoint")
    parser.add_argument("--set_size", type=int, default=16, help="Set size for encoding held-out controls")
    parser.add_argument(
        "--log_path",
        type=str,
        default="/orcd/archive/abugoot/001/Projects/paolo/CoupledDistributionEmbeddings/virus_eval/script3_forecast_logger.log",
    )
    args = parser.parse_args()

    logger = setup_file_logger("virus_eval.script3_forecast", logfile_path=args.log_path)

    # Resolve run directory and config; set up encoder and predictor
    run_dir = resolve_outputs_dir(args.outputs_subdir)
    cfg = load_cfg_from_run_dir(run_dir)
    device = torch.device(args.device)

    encoder, predictor = instantiate_models(cfg, device, logger)
    load_weights(encoder, predictor, run_dir, device, logger, require_predictor=True)

    # Load timepoint models trained in script 2 (latent -> index)
    mlp_path = os.path.join(args.models_dir, "mlp_sourceidx.pt")
    ridge_path = os.path.join(args.models_dir, "ridge_sourceidx.npz")
    if not os.path.exists(mlp_path) or not os.path.exists(ridge_path):
        raise FileNotFoundError("Trained models from script 2 not found.")

    mlp_payload = torch.load(mlp_path, map_location="cpu")
    mlp = IdxMLP(input_dim=int(mlp_payload["input_dim"]))
    mlp.load_state_dict(mlp_payload["state_dict"])
    mlp.to(device)
    mlp.eval()

    ridge_payload = np.load(ridge_path)
    ridge_coef = ridge_payload["coef"].astype(np.float32)
    ridge_intercept = float(ridge_payload["intercept"][0])

    def ridge_predict(x: np.ndarray) -> np.ndarray:
        return x @ ridge_coef + ridge_intercept

    # Load script1 dataset with pair-grouped arrays to find the last (src_idx, tgt_idx) pair
    data = np.load(args.dataset_path, allow_pickle=True)
    if ("pair_keys" not in data) or ("grouped_true_target_latents" not in data):
        raise RuntimeError("Dataset must contain 'pair_keys' and 'grouped_true_target_latents'.")
    pair_keys = data["pair_keys"].astype(np.int64)  # shape [M, 2]
    grouped_true_tgt = data["grouped_true_target_latents"].astype(object)

    if pair_keys.shape[0] == 0:
        raise RuntimeError("No pairs found in dataset.")

    # Choose the 'last' pair in the sorted order used by script1
    last_idx = pair_keys.shape[0] - 1
    src_idx_last, tgt_idx_last = int(pair_keys[last_idx, 0]), int(pair_keys[last_idx, 1])
    latents_for_last_pair = grouped_true_tgt[last_idx]
    if latents_for_last_pair is None or latents_for_last_pair.size == 0:
        raise RuntimeError("No true target latents found for the last pair.")
    latents_for_last_pair = latents_for_last_pair.astype(np.float32)

    logger.info(
        f"Forecasting from last available target idx={tgt_idx_last} to held-out idx={tgt_idx_last + 1} using predictor"
    )

    # Forecast: use true target latents of the last pair as the predictor input x,
    # and condition with (source_idx = tgt_idx_last, target_idx = tgt_idx_last + 1)
    with torch.no_grad():
        xb = torch.from_numpy(latents_for_last_pair).to(device)
        d1 = torch.full((xb.shape[0],), fill_value=float(tgt_idx_last), device=device, dtype=torch.float32)
        d2 = torch.full((xb.shape[0],), fill_value=float(tgt_idx_last + 1), device=device, dtype=torch.float32)
        if getattr(predictor, "requires_condition", False):
            yb = predictor(xb, condition_scalars=(d1, d2))
        else:
            yb = predictor(xb)
        forecast_latents = yb.detach().cpu().numpy().astype(np.float32)

    # Map forecast latents to indices via script2 models
    with torch.no_grad():
        mlp_forecast = mlp(torch.from_numpy(forecast_latents).to(device)).detach().cpu().numpy()
    ridge_forecast = ridge_predict(forecast_latents)

    mlp_forecast_mean = float(np.mean(mlp_forecast))
    mlp_forecast_std = float(np.std(mlp_forecast))
    mlp_forecast_round = int(np.rint(mlp_forecast_mean))

    ridge_forecast_mean = float(np.mean(ridge_forecast))
    ridge_forecast_std = float(np.std(ridge_forecast))
    ridge_forecast_round = int(np.rint(ridge_forecast_mean))

    logger.info(
        f"Forecast via predictor -> index: MLP mean±std={mlp_forecast_mean:.2f}±{mlp_forecast_std:.2f} (rounded={mlp_forecast_round}), "
        f"Ridge mean±std={ridge_forecast_mean:.2f}±{ridge_forecast_std:.2f} (rounded={ridge_forecast_round}) | "
        f"ground_truth_target_idx={tgt_idx_last + 1}"
    )

    # Control: encode held-out last timepoint directly with encoder (5 random sets of size set_size)
    tokenized = torch.load(args.heldout_path)
    if not isinstance(tokenized, list) or len(tokenized) == 0:
        raise RuntimeError("Held-out PT file must contain a non-empty list.")
    heldout_item = tokenized[-1]
    if "samples" not in heldout_item:
        raise KeyError("Held-out item missing 'samples'.")
    esm_ids_full = _ensure_tensor(heldout_item["samples"]["esm_input_ids"])  # [N, L]
    esm_mask_full = _ensure_tensor(heldout_item["samples"]["esm_attention_mask"])  # [N, L]
    if esm_ids_full.shape[0] < args.set_size:
        raise RuntimeError("Held-out timepoint has fewer sequences than set_size.")

    control_latents: List[np.ndarray] = []
    rng = np.random.RandomState(0)
    for _ in range(args.num_control_sets):
        # Sample a set of size set_size without replacement
        idx = torch.from_numpy(rng.permutation(esm_ids_full.shape[0])[: args.set_size])
        ids_subset = esm_ids_full.index_select(dim=0, index=idx)
        mask_subset = esm_mask_full.index_select(dim=0, index=idx)
        sample_entry: Dict = {
            "source_samples": {
                "esm_input_ids": ids_subset,
                "esm_attention_mask": mask_subset,
            }
        }
        with torch.no_grad():
            lat = encode_source_samples(
                encoder=encoder,
                sample_entry=sample_entry,
                device=device,
                target_set_size=args.set_size,
            )  # [D]
        control_latents.append(lat.numpy().astype(np.float32))

    control_latents_np = np.stack(control_latents, axis=0).astype(np.float32)  # [num_sets, D]

    with torch.no_grad():
        mlp_control = mlp(torch.from_numpy(control_latents_np).to(device)).detach().cpu().numpy()
    ridge_control = ridge_predict(control_latents_np)

    mlp_control_mean = float(np.mean(mlp_control))
    mlp_control_std = float(np.std(mlp_control))
    mlp_control_round = int(np.rint(mlp_control_mean))

    ridge_control_mean = float(np.mean(ridge_control))
    ridge_control_std = float(np.std(ridge_control))
    ridge_control_round = int(np.rint(ridge_control_mean))

    logger.info(
        f"Control (encoder on held-out) -> index: MLP mean±std={mlp_control_mean:.2f}±{mlp_control_std:.2f} (rounded={mlp_control_round}), "
        f"Ridge mean±std={ridge_control_mean:.2f}±{ridge_control_std:.2f} (rounded={ridge_control_round}) | "
        f"expected_target_idx={tgt_idx_last + 1}"
    )

    # Side-by-side summary
    logger.info(
        f"Summary | ground_truth_target_idx={tgt_idx_last + 1} | "
        f"Forecast: MLP {mlp_forecast_mean:.2f}±{mlp_forecast_std:.2f} (rnd={mlp_forecast_round}), "
        f"Ridge {ridge_forecast_mean:.2f}±{ridge_forecast_std:.2f} (rnd={ridge_forecast_round}) | "
        f"Control: MLP {mlp_control_mean:.2f}±{mlp_control_std:.2f} (rnd={mlp_control_round}), "
        f"Ridge {ridge_control_mean:.2f}±{ridge_control_std:.2f} (rnd={ridge_control_round})"
    )


if __name__ == "__main__":
    main()


