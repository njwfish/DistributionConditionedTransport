#!/usr/bin/env python3
"""
Parse evaluation log files and extract final metrics into a CSV file.

This script reads log files from the logs/ directory that are generated by
run_evaluate_trellis_all_metrics.sh, run_evaluate_trellis_all_metrics_mfm.sh,
and run_evaluate_trellis_all_metrics_oracle.sh and extracts the final model 
metrics for each combination of:
- method: ours, mfm, oracle
- metric: mmd_energy, mmd_rbf, swd  
- split: replicas-1, replicas-2, pdo21, pdo27, pdo75

Usage:
    python parse_evaluation_logs.py --generator swd
    python parse_evaluation_logs.py --generator energy
"""

import os
import re
import csv
import glob
import argparse
from pathlib import Path
from typing import Dict, List, Optional, Tuple


def parse_log_file(filepath: str) -> Optional[Dict]:
    """
    Parse a single log file and extract the relevant information.
    
    Returns a dict with:
        - split: the data split name
        - metric: the metric name (lowercase)
        - model_mean: the mean model score
        - model_std: the std of model score
        - baseline_mean: the mean baseline score (if available)
        - baseline_std: the std of baseline score (if available)
    
    Returns None if the file cannot be parsed or is incomplete.
    """
    try:
        with open(filepath, 'r') as f:
            content = f.read()
    except Exception as e:
        print(f"Error reading {filepath}: {e}")
        return None
    
    result = {}
    
    # Extract split and metric from the first line
    # Format: "Job X: Evaluating split=..., metric=..."
    job_match = re.search(r'Job \d+: Evaluating split=([^,]+), metric=(\w+)', content)
    if not job_match:
        print(f"Could not find job info in {filepath}")
        return None
    
    result['split'] = job_match.group(1)
    result['metric'] = job_match.group(2).lower()
    
    # Find the FINAL RESULTS section and extract the metric line
    # Look for lines like:
    # MMD_ENERGY Model:    0.0923 +/- 0.0941  Baseline:    0.2256 +/- 0.2788
    # SWD    Model:    0.2379 +/- 0.0863
    
    # Find the final results section
    final_section = re.search(r'FINAL RESULTS.*?={20,}(.*)', content, re.DOTALL)
    if not final_section:
        print(f"Could not find FINAL RESULTS section in {filepath}")
        return None
    
    final_content = final_section.group(1)
    
    # Pattern for metric line with optional baseline
    # Handles: MMD_ENERGY, MMD_RBF, SWD
    metric_pattern = r'(MMD_ENERGY|MMD_RBF|SWD)\s+Model:\s+([\d.]+)\s*\+/-\s*([\d.]+)(?:\s+Baseline:\s+([\d.]+)\s*\+/-\s*([\d.]+))?'
    
    metric_match = re.search(metric_pattern, final_content)
    if not metric_match:
        print(f"Could not find metric line in FINAL RESULTS of {filepath}")
        return None
    
    result['metric_name'] = metric_match.group(1).lower().replace('_', '_')
    result['model_mean'] = float(metric_match.group(2))
    result['model_std'] = float(metric_match.group(3))
    
    if metric_match.group(4) and metric_match.group(5):
        result['baseline_mean'] = float(metric_match.group(4))
        result['baseline_std'] = float(metric_match.group(5))
    else:
        result['baseline_mean'] = None
        result['baseline_std'] = None
    
    return result


def extract_method_from_filename(filename: str) -> Optional[str]:
    """Extract the method (ours, mfm, or oracle) from the filename."""
    basename = os.path.basename(filename)
    if basename.startswith('o_ours_'):
        return 'ours'
    elif basename.startswith('o_mfm_'):
        return 'mfm'
    elif basename.startswith('o_oracle_'):
        return 'oracle'
    return None


def get_generator_model_from_filename(filename: str) -> Optional[str]:
    """
    Extract the generator model type from the log filename.
    
    Log files are named like: o_ours_energy_0, o_mfm_swd_14, etc.
    The generator model is the part after the method (energy, swd, etc.).
    This indicates which generator model was being evaluated, NOT the metric.
    """
    basename = os.path.basename(filename)
    # Pattern: o_<method>_<generator_model>_<job_id>
    match = re.match(r'o_(?:ours|mfm)_(energy|swd|rbf)_\d+', basename)
    if match:
        return match.group(1)
    return None


def main():
    parser = argparse.ArgumentParser(description='Parse evaluation log files and extract metrics to CSV.')
    parser.add_argument('--generator', type=str, required=True, choices=['swd', 'energy', 'fm'],
                        help='Generator model to look for (swd, energy, or fm)')
    args = parser.parse_args()
    
    generator = args.generator
    logs_dir = Path(__file__).parent / 'logs'
    
    # Look at log files from the specified generator model evaluation
    # Files are named: o_<method>_<generator>_<job_id>
    log_patterns = [
        str(logs_dir / f'o_ours_{generator}_*'),
        str(logs_dir / f'o_mfm_{generator}_*'),
        str(logs_dir / f'o_oracle_{generator}_*'),
    ]
    
    log_files = []
    for pattern in log_patterns:
        log_files.extend(glob.glob(pattern))
    
    print(f"Found {len(log_files)} log files to process ({generator.upper()} generator model)")
    
    # Store all parsed results
    results = []
    
    for filepath in sorted(log_files):
        method = extract_method_from_filename(filepath)
        if method is None:
            print(f"Skipping {filepath}: could not determine method")
            continue
        
        parsed = parse_log_file(filepath)
        if parsed is None:
            print(f"Skipping {filepath}: could not parse")
            continue
        
        results.append({
            'method': method,
            'split': parsed['split'],
            'metric': parsed['metric'],
            'model_mean': parsed['model_mean'],
            'model_std': parsed['model_std'],
            'baseline_mean': parsed['baseline_mean'],
            'baseline_std': parsed['baseline_std'],
            'log_file': os.path.basename(filepath),
        })
    
    print(f"\nSuccessfully parsed {len(results)} log files")
    
    # Sort results for consistent output
    results.sort(key=lambda x: (x['method'], x['split'], x['metric']))
    
    # Write to CSV (excluding internal fields)
    output_csv = logs_dir.parent / f'evaluation_results_{generator}.csv'
    
    fieldnames = ['method', 'split', 'metric', 'model_mean', 'model_std', 
                  'baseline_mean', 'baseline_std', 'log_file']
    
    with open(output_csv, 'w', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames, extrasaction='ignore')
        writer.writeheader()
        writer.writerows(results)
    
    print(f"\nResults saved to: {output_csv}")
    
    # Print a summary table
    print("\n" + "="*100)
    print(f"SUMMARY TABLE ({generator.upper()} generator)")
    print("="*100)
    
    # Group by method, split, metric
    splits = ['replicas-1', 'replicas-2', 'pdo21', 'pdo27', 'pdo75']
    metrics = ['mmd_energy', 'mmd_rbf', 'swd']
    methods = ['ours', 'mfm', 'oracle']
    
    # Create lookup dict
    lookup = {}
    for r in results:
        key = (r['method'], r['split'], r['metric'])
        lookup[key] = r
    
    # Print table header
    print(f"\n{'Method':<8} {'Split':<12} {'Metric':<12} {'Model Mean':<12} {'Model Std':<12} {'Baseline Mean':<14} {'Baseline Std':<14}")
    print("-"*86)
    
    for method in methods:
        has_any = any((method, split, metric) in lookup for split in splits for metric in metrics)
        if not has_any:
            print(f"{method:<8} (no data found)")
            print()
            continue
            
        for split in splits:
            for metric in metrics:
                key = (method, split, metric)
                if key in lookup:
                    r = lookup[key]
                    baseline_mean = f"{r['baseline_mean']:.6f}" if r['baseline_mean'] is not None else 'N/A'
                    baseline_std = f"{r['baseline_std']:.6f}" if r['baseline_std'] is not None else 'N/A'
                    print(f"{method:<8} {split:<12} {metric:<12} {r['model_mean']:<12.6f} {r['model_std']:<12.6f} {baseline_mean:<14} {baseline_std:<14}")
                else:
                    print(f"{method:<8} {split:<12} {metric:<12} {'MISSING':<12} {'MISSING':<12} {'MISSING':<14} {'MISSING':<14}")
        print()  # Blank line between methods


if __name__ == '__main__':
    main()
