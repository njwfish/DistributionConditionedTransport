import os
import argparse
from typing import Tuple, Dict, List

import numpy as np
import torch
from sklearn.linear_model import Ridge
from sklearn.metrics import mean_squared_error

from virus_eval.utils import IdxMLP, setup_file_logger


def split_train_val_test_pairs(num_pairs: int, seed: int = 42) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    rs = np.random.RandomState(seed)
    perm = rs.permutation(num_pairs)
    n_train = int(0.8 * num_pairs)
    n_val = int(0.1 * num_pairs)
    n_test = num_pairs - n_train - n_val
    train_idx = perm[:n_train]
    val_idx = perm[n_train:n_train + n_val]
    test_idx = perm[n_train + n_val:]
    return train_idx, val_idx, test_idx


def main():
    parser = argparse.ArgumentParser(description="Script 2: Train MLP and Ridge to predict source indices from source latents (pair-based splits)")
    parser.add_argument("dataset_path", type=str, help="Path to dataset .npz generated by script 1")
    parser.add_argument("--device", type=str, default="cuda" if torch.cuda.is_available() else "cpu")
    parser.add_argument("--mlp_epochs", type=int, default=200)
    parser.add_argument("--mlp_lr", type=float, default=1e-3)
    parser.add_argument("--mlp_batch_size", type=int, default=128)
    parser.add_argument("--mlp_patience", type=int, default=20)
    parser.add_argument("--ridge_alpha", type=float, default=1.0)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument(
        "--save_dir",
        type=str,
        default="/orcd/archive/abugoot/001/Projects/paolo/CoupledDistributionEmbeddings/virus_eval",
        help="Directory to save trained models and logs",
    )
    args = parser.parse_args()

    os.makedirs(args.save_dir, exist_ok=True)
    log_path = os.path.join(args.save_dir, "script2_logger.log")
    logger = setup_file_logger("virus_eval.script2", logfile_path=log_path)

    data = np.load(args.dataset_path, allow_pickle=True)
    # Prefer pair-grouped arrays if present
    use_pairs = True #("pair_keys" in data) and ("grouped_source_latents" in data)
    if use_pairs:
        pair_keys = data["pair_keys"].astype(np.int64)  # shape [M, 2]
        grouped_source_latents = data["grouped_source_latents"].astype(object)  # each [k_i, D]
        # Build per-pair label arrays (source_idx for every element in the pair group)
        num_pairs = pair_keys.shape[0]
        logger.info(f"Loaded dataset with pair-grouped arrays: num_pairs={num_pairs}")

        # Split by pairs
        tr_pairs, va_pairs, te_pairs = split_train_val_test_pairs(num_pairs, seed=args.seed)

        def flatten_pairs(sel_pairs: np.ndarray) -> Tuple[np.ndarray, np.ndarray]:
            feats: List[np.ndarray] = []
            labels: List[np.ndarray] = []
            for idx in sel_pairs.tolist():
                src_idx_val = int(pair_keys[idx, 0])
                latents_arr = grouped_source_latents[idx]
                if latents_arr is None or latents_arr.size == 0:
                    continue
                feats.append(latents_arr.astype(np.float32))
                labels.append(np.full((latents_arr.shape[0],), src_idx_val, dtype=np.float32))
            if len(feats) == 0:
                return np.zeros((0, 0), dtype=np.float32), np.zeros((0,), dtype=np.float32)
            x = np.concatenate(feats, axis=0)
            y = np.concatenate(labels, axis=0)
            # Shuffle
            rs = np.random.RandomState(1234)
            perm = rs.permutation(x.shape[0])
            return x[perm], y[perm]

        x_train, y_train = flatten_pairs(tr_pairs)
        x_val, y_val = flatten_pairs(va_pairs)
        x_test, y_test = flatten_pairs(te_pairs)
        if x_train.ndim != 2:
            raise RuntimeError("Training features have invalid shape after pair flattening.")
        n, d = x_train.shape[0] + x_val.shape[0] + x_test.shape[0], x_train.shape[1]
        logger.info(f"Constructed train/val/test by pairs with total N={n}, D={d}")
    else:
        source_latents = data["source_latents"].astype(np.float32)
        source_indices = data["source_indices"].astype(np.float32)
        n, d = source_latents.shape
        logger.info(f"Loaded legacy dataset (flat arrays): N={n}, D={d}")

        # Legacy: random flat split by samples
        rs = np.random.RandomState(args.seed)
        perm = rs.permutation(n)
        n_train = int(0.8 * n)
        n_val = int(0.1 * n)
        train_idx = perm[:n_train]
        val_idx = perm[n_train:n_train + n_val]
        test_idx = perm[n_train + n_val:]
        x_train, y_train = source_latents[train_idx], source_indices[train_idx]
        x_val, y_val = source_latents[val_idx], source_indices[val_idx]
        x_test, y_test = source_latents[test_idx], source_indices[test_idx]

    device = torch.device(args.device)

    # Train MLP with early stopping using validation set
    mlp = IdxMLP(input_dim=int(d)).to(device)
    opt = torch.optim.Adam(mlp.parameters(), lr=args.mlp_lr)
    loss_fn = torch.nn.MSELoss()

    x_tr = torch.from_numpy(x_train).to(device)
    y_tr = torch.from_numpy(y_train).to(device)
    x_va = torch.from_numpy(x_val).to(device)
    y_va = torch.from_numpy(y_val).to(device)

    train_ds = torch.utils.data.TensorDataset(x_tr, y_tr)
    val_ds = torch.utils.data.TensorDataset(x_va, y_va)
    train_loader = torch.utils.data.DataLoader(train_ds, batch_size=args.mlp_batch_size, shuffle=True)
    val_loader = torch.utils.data.DataLoader(val_ds, batch_size=args.mlp_batch_size, shuffle=False)

    best_val = float("inf")
    best_state = None
    no_improve = 0

    for epoch in range(1, args.mlp_epochs + 1):
        mlp.train()
        tr_loss = 0.0
        for xb, yb in train_loader:
            opt.zero_grad()
            pred = mlp(xb)
            loss = loss_fn(pred, yb)
            loss.backward()
            opt.step()
            tr_loss += float(loss.detach().item()) * xb.shape[0]
        tr_loss /= max(1, x_train.shape[0])

        mlp.eval()
        va_loss = 0.0
        with torch.no_grad():
            for xb, yb in val_loader:
                pred = mlp(xb)
                loss = loss_fn(pred, yb)
                va_loss += float(loss.detach().item()) * xb.shape[0]
        va_loss /= max(1, x_val.shape[0])

        if epoch % 10 == 0 or epoch == 1:
            logger.info(f"MLP epoch {epoch:03d} | train_loss={tr_loss:.4f} val_loss={va_loss:.4f}")

        if va_loss + 1e-8 < best_val:
            best_val = va_loss
            best_state = {k: v.detach().cpu().clone() for k, v in mlp.state_dict().items()}
            no_improve = 0
        else:
            no_improve += 1
            if no_improve >= args.mlp_patience:
                logger.info(f"Early stopping at epoch {epoch}")
                break

    if best_state is not None:
        mlp.load_state_dict(best_state)

    # Evaluate on train/val/test for MLP
    def eval_split(x_split: np.ndarray, y_split: np.ndarray) -> Tuple[float, np.ndarray]:
        with torch.no_grad():
            preds = mlp(torch.from_numpy(x_split).to(device)).detach().cpu().numpy()
        mse = float(mean_squared_error(y_split, preds))
        return mse, preds

    train_mse, _ = eval_split(x_train, y_train)
    val_mse, _ = eval_split(x_val, y_val)
    test_mse, test_preds_mlp = eval_split(x_test, y_test)

    logger.info(f"MLP performance | train MSE={train_mse:.4f} | val MSE={val_mse:.4f} | test MSE={test_mse:.4f}")
    # Side-by-side for test set
    logger.info("MLP test set predictions (true_label, prediction):")
    for i in range(len(y_test)):
        logger.info(f"true={int(y_test[i])} pred={test_preds_mlp[i]:.3f}")

    # Train ridge regression
    ridge = Ridge(alpha=args.ridge_alpha, random_state=args.seed)
    ridge.fit(x_train, y_train)
    ridge_train_preds = ridge.predict(x_train)
    ridge_val_preds = ridge.predict(x_val)
    ridge_test_preds = ridge.predict(x_test)
    ridge_train_mse = float(mean_squared_error(y_train, ridge_train_preds))
    ridge_val_mse = float(mean_squared_error(y_val, ridge_val_preds))
    ridge_test_mse = float(mean_squared_error(y_test, ridge_test_preds))

    logger.info(
        f"Ridge performance | train MSE={ridge_train_mse:.4f} | val MSE={ridge_val_mse:.4f} | test MSE={ridge_test_mse:.4f}"
    )
    logger.info("Ridge test set predictions (true_label, prediction):")
    for i in range(len(y_test)):
        logger.info(f"true={int(y_test[i])} pred={ridge_test_preds[i]:.3f}")

    # Save models
    mlp_path = os.path.join(args.save_dir, "mlp_sourceidx.pt")
    torch.save({"state_dict": mlp.state_dict(), "input_dim": d}, mlp_path)
    logger.info(f"Saved MLP to {mlp_path}")

    ridge_path = os.path.join(args.save_dir, "ridge_sourceidx.npz")
    # Save ridge coefficients and intercept to reload later
    np.savez_compressed(ridge_path, coef=ridge.coef_.astype(np.float32), intercept=np.array([ridge.intercept_], dtype=np.float32))
    logger.info(f"Saved Ridge to {ridge_path}")


if __name__ == "__main__":
    main()


