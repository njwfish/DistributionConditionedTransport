    def get_vocab_size(self):
        """Get the vocabulary size for the encoded sequences.
        
        Since we encode as alternating states and actions (s_1, a_1, s_2, a_2, ...),
        the vocabulary size is max(n_states, n_actions).
        """
        return max(self.n_states, self.n_actions)
    
    def get_state_action_vocab_size(self):
        """Get the vocabulary size for state-action pairs (legacy method)."""
        return self.n_states * self.n_actions
    
    def get_transition_matrix(self, set_idx):
        """Get the transition matrix for a specific set.
        
        Args:
            set_idx: Index of the set
            
        Returns:
            Transition matrix of shape (n_states, n_actions, n_states)
        """
        return self.transition_matrices[set_idx]
    
    def get_all_transition_matrices(self):
        """Get all transition matrices.
        
        Returns:
            Tensor of shape (n_sets, n_states, n_actions, n_states)
        """
        return self.transition_matrices
    
    def encode_state_action_pairs(self, trajectory_set):
        """Encode trajectories as flattened sequences: s_1, a_1, s_2, a_2, ...
        
        Args:
            trajectory_set: Tensor of shape (set_size, trajectory_length, 2)
            
        Returns:
            Tensor of shape (set_size, trajectory_length * 2) with alternating states and actions
        """
        batch_size, traj_len, _ = trajectory_set.shape
        
        # Flatten to alternating sequence: s_1, a_1, s_2, a_2, ...
        # trajectory_set is (set_size, trajectory_length, 2) where last dim is [state, action]
        encoded = trajectory_set.view(batch_size, traj_len * 2)
        
        return encoded.long()
    
    def decode_state_action_pairs(self, encoded_trajectory_set):
        """Decode flattened sequences back to state-action pairs.
        
        Args:
            encoded_trajectory_set: Tensor of shape (set_size, trajectory_length * 2)
            
        Returns:
            Tensor of shape (set_size, trajectory_length, 2)
        """
        batch_size, seq_len = encoded_trajectory_set.shape
        traj_len = seq_len // 2
        
        # Reshape from (set_size, trajectory_length * 2) to (set_size, trajectory_length, 2)
        decoded = encoded_trajectory_set.view(batch_size, traj_len, 2)
        
        return decoded

